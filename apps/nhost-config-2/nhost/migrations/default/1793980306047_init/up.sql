SET transaction_timeout = 0;
SET check_function_bodies = false;
CREATE FUNCTION public.set_current_timestamp_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
  _new record;
BEGIN
  _new := NEW;
  _new."updated_at" = NOW();
  RETURN _new;
END;
$$;
CREATE TABLE public.items (
    id uuid DEFAULT gen_random_uuid() NOT NULL,
    title text NOT NULL,
    status_id text NOT NULL,
    sort_order double precision DEFAULT 0 NOT NULL,
    flagged boolean DEFAULT false NOT NULL,
    description text DEFAULT ''::text NOT NULL,
    criteria jsonb DEFAULT '[]'::jsonb NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    seq_id integer NOT NULL
);
CREATE TABLE public.items_assignees (
    item_id uuid NOT NULL,
    user_id uuid NOT NULL
);
ALTER TABLE public.items ALTER COLUMN seq_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.items_seq_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY public.items_assignees
    ADD CONSTRAINT items_assignees_pkey PRIMARY KEY (item_id, user_id);
ALTER TABLE ONLY public.items
    ADD CONSTRAINT items_pkey PRIMARY KEY (id);
CREATE TRIGGER set_public_items_updated_at BEFORE UPDATE ON public.items FOR EACH ROW EXECUTE FUNCTION public.set_current_timestamp_updated_at();
COMMENT ON TRIGGER set_public_items_updated_at ON public.items IS 'trigger to set value of column "updated_at" to current timestamp on row update';
ALTER TABLE ONLY public.items_assignees
    ADD CONSTRAINT items_assignees_item_id_fkey FOREIGN KEY (item_id) REFERENCES public.items(id) ON UPDATE RESTRICT ON DELETE CASCADE;
ALTER TABLE ONLY public.items_assignees
    ADD CONSTRAINT items_assignees_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id) ON UPDATE RESTRICT ON DELETE RESTRICT;
